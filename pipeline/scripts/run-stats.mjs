#!/usr/bin/env node
// Aggregate statistics of the real week-1 CEO runs, from each run's report.json only (no course content):
// calls, model time, tokens, reviewer verdicts and severities, revision rounds, P5 gate rounds, outcome.
//   node scripts/run-stats.mjs <runs-dir> [--out docs/week1-run-stats]
// The private runs directory is not part of this repository; the output files are.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const args = process.argv.slice(2);
const runsDir = args[0];
const out = args.includes('--out') ? args[args.indexOf('--out') + 1] : null;
if (!runsDir) { console.error('Usage: node scripts/run-stats.mjs <runs-dir> [--out <prefix>]'); process.exit(2); }

const KIND = { javitas: 'production', t27: 'French-life round' };
const runs = [];
for (const d of readdirSync(runsDir).sort()) {
  const m = /^(javitas|t27)-([A-Z]+\d+[a-z]?)-(\d{4}-\d{2}-\d{2})/.exec(d);
  const file = join(runsDir, d, 'report.json');
  if (!m || !existsSync(file)) continue;
  const r = JSON.parse(readFileSync(file, 'utf8'));
  const steps = r.steps.filter(s => s.status === 'DONE');
  const reviews = steps.filter(s => s.summary?.verdict);
  const sum = k => reviews.reduce((a, s) => a + (Number(s.summary[k]) || 0), 0);
  runs.push({
    run: d, unit: m[2], kind: KIND[m[1]], date: m[3], outcome: r.outcome,
    calls: r.calls, modelHours: +(r.totalModelSeconds / 3600).toFixed(2),
    wallHours: r.finishedAt ? +((Date.parse(r.finishedAt) - Date.parse(r.createdAt)) / 3.6e6).toFixed(1) : null,
    tokens: typeof r.tokens === 'number' ? r.tokens : null,
    authorSteps: steps.filter(s => !s.summary?.verdict && s.role !== 'SOLVER').length,
    reviewSteps: reviews.length,
    revisionRequired: reviews.filter(s => s.summary.verdict === 'REVISION_REQUIRED').length,
    reviewPass: reviews.filter(s => s.summary.verdict === 'REVIEW_PASS').length,
    blocker: sum('blocker'), major: sum('major'), minor: sum('minor'),
    revisionRounds: steps.filter(s => /-rev\d+$/.test(s.id)).length,
    rewrites: steps.filter(s => /-e\d+$/.test(s.id)).length,
    p5FixRounds: steps.filter(s => /-p5-javitas\d+$/.test(s.id)).length,
    solverCalls: steps.filter(s => s.role === 'SOLVER').length,
    roles: Object.fromEntries([...new Set(steps.map(s => s.role))].map(role => [role, steps.filter(s => s.role === role).length])),
  });
}

const total = (list, k) => list.reduce((a, r) => a + (r[k] ?? 0), 0);
const byRole = {};
for (const r of runs) for (const [role, n] of Object.entries(r.roles)) byRole[/^[URGV]T?\d/.test(role) ? 'unit writer' : role] = (byRole[/^[URGV]T?\d/.test(role) ? 'unit writer' : role] ?? 0) + n;
const summary = {
  runs: runs.length, units: new Set(runs.map(r => r.unit)).size,
  completed: runs.filter(r => r.outcome === 'COMPLETED').length,
  blockedAtP5: runs.filter(r => r.outcome === 'BLOCKED_P5_GATE').length,
  calls: total(runs, 'calls'), modelHours: +total(runs, 'modelHours').toFixed(1),
  tokensMeasured: total(runs, 'tokens'), runsWithTokens: runs.filter(r => r.tokens != null).length,
  reviewSteps: total(runs, 'reviewSteps'), revisionRequired: total(runs, 'revisionRequired'),
  blocker: total(runs, 'blocker'), major: total(runs, 'major'), minor: total(runs, 'minor'),
  p5FixRounds: total(runs, 'p5FixRounds'), solverCalls: total(runs, 'solverCalls'), byRole,
};

const md = [
  '# Week-1 production runs: aggregate statistics',
  '',
  `Generated by \`pipeline/scripts/run-stats.mjs\` from the \`report.json\` of each real CEO run (${runs.map(r => r.date).sort()[0]} – ${runs.map(r => r.date).sort().at(-1)}).`,
  'Only counts are published here; the runs themselves stay private, except the U21 example in `pipeline/examples/`.',
  'Model time is the sum of call durations; calls ran from flat-rate subscriptions (Claude Code, Codex CLI), so there is no per-call bill.',
  '',
  '| Measure | Value |', '|---|---|',
  `| Runs / distinct units | ${summary.runs} / ${summary.units} |`,
  `| Outcome COMPLETED / BLOCKED_P5_GATE | ${summary.completed} / ${summary.blockedAtP5} |`,
  `| Model calls | ${summary.calls} |`,
  `| Model time (sum of calls) | ${summary.modelHours} h |`,
  `| Tokens (only ${summary.runsWithTokens} runs report them) | ${(summary.tokensMeasured / 1e6).toFixed(0)} M |`,
  `| Review steps / of which REVISION_REQUIRED | ${summary.reviewSteps} / ${summary.revisionRequired} (${Math.round(100 * summary.revisionRequired / summary.reviewSteps)}%) |`,
  `| Findings reported by reviewers: blocker / major / minor | ${summary.blocker} / ${summary.major} / ${summary.minor} |`,
  `| P5 gate fix rounds | ${summary.p5FixRounds} |`,
  `| Independent solver calls | ${summary.solverCalls} |`,
  '',
  '**Calls by role:** ' + Object.entries(byRole).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ') + '.',
  '',
  'A `BLOCKED_P5_GATE` run stopped because the deterministic gates still failed after the allowed fix rounds;',
  'the unit was then finished in a later run or by a targeted fix. Findings are as reported by the LLM reviewers, not audited.',
  '',
  '| Run | Kind | Outcome | Calls | Model h | Wall h | Reviews (revise/pass) | B/M/m findings | Revision rounds | Rewrites | P5 fix rounds |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
  ...runs.map(r => `| ${r.run} | ${r.kind} | ${r.outcome} | ${r.calls} | ${r.modelHours} | ${r.wallHours ?? '—'} | ${r.revisionRequired}/${r.reviewPass} | ${r.blocker}/${r.major}/${r.minor} | ${r.revisionRounds} | ${r.rewrites} | ${r.p5FixRounds} |`),
  '',
].join('\n');

if (out) {
  writeFileSync(`${out}.md`, md);
  writeFileSync(`${out}.json`, `${JSON.stringify({ summary, runs }, null, 2)}\n`);
  console.log(`Wrote ${out}.md and ${out}.json (${runs.length} runs).`);
} else console.log(md);
